-- ============================================================================
-- 007_kpi_metrics_source_columns.sql
--
-- КРИТИЧНЫЙ ФИКС бага «Цели не создаются, при нажатии ничего не
-- происходит» (сообщено 24 августа 2026).
--
-- В раунде 6 (тест-стенд автозачёта) API показателей
-- (pages/api/company-admin/kpi/metrics.js) стал писать поля `source` и
-- `source_config` при КАЖДОМ сохранении показателя — не только при
-- включённом авто-источнике, а вообще всегда, для любого способа
-- создания/редактирования цели. lib/kpiSource.js (написан ещё до этой
-- сессии) уже читал эти поля, и это ошибочно показалось достаточным
-- подтверждением, что столбцы существуют в БД — но нигде раньше не было
-- ни одной миграции, которая бы их реально создавала. Если в вашей базе
-- этих столбцов не было, любая вставка в kpi_metrics с этого момента
-- падала с ошибкой Postgres «column does not exist» — то есть создание
-- ЛЮБОЙ цели (не только с авто-источником) было сломано.
--
-- Столбцы nullable/со значением по умолчанию — если они уже существуют
-- (вдруг всё-таки были), эта миграция ничего не меняет и безопасна для
-- повторного запуска.
-- ============================================================================

alter table public.kpi_metrics
  add column if not exists source text not null default 'manual';

alter table public.kpi_metrics
  add column if not exists source_config jsonb;

comment on column public.kpi_metrics.source is
  'manual (значения вводятся вручную/через bulk-загрузку) или auto '
  '(подтягиваются по расписанию из source_config.url — см. '
  'lib/kpiSource.js и pages/api/cron/check-deadlines.js, секция 5).';

notify pgrst, 'reload schema';
