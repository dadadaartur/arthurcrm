-- ============================================================================
-- 005_flexible_kpi_thresholds.sql
--
-- Часть 1 — гибкие пороги (п.5 ТЗ от 24 августа 2026).
--
-- Раньше у каждого показателя (kpi_metrics) было ровно 4 жёстко зашитых
-- столбца-порога: thr_min/thr_mid/thr_top/thr_ultra (и парные им
-- energy_*/karma_*). Это не позволяло руководителю задать своё число
-- уровней.
--
-- Решение — НЕ переносить данные в отдельную таблицу (это потребовало бы
-- миграции существующих строк и переписывания каждого запроса, который их
-- читает). Вместо этого — один новый nullable JSONB-столбец `thresholds`.
-- Если он NULL — показатель продолжает работать по старым 4 столбцам
-- ровно как раньше (обратная совместимость, НИКАКИХ данных не меняется и
-- не мигрирует). Если он задан — это список произвольной длины вида:
--   [{"key":"min","label":"Минимум","value":5,"color":"#f97316","karma":1,"energy":5}, ...]
-- Код на чтение (lib/kpi.js: resolveThresholds/bandFor/energyFor/karmaFor)
-- уже написан с этой обратной совместимостью — см. соответствующий раунд
-- в CHANGELOG.md.
--
-- Часть 2 — точный таргетинг авто-заданий по одному показателю (п.4 ТЗ).
--
-- У tasks уже был столбец auto_metric_id (внешний ключ на kpi_metrics),
-- но он нигде не читался в коде — единственный режим авто-задания был
-- «все показатели» / «любой один». Добавляем auto_target_rank: сколько
-- порогов подряд (считая с самого мягкого) должен достичь сотрудник по
-- ИМЕННО ЭТОМУ показателю. Ранг, а не название уровня (не 'min'/'ultra')
-- — специально, чтобы работать и с произвольными кастомными порогами из
-- части 1, у которых может не быть уровня с названием "min" вообще.
-- ============================================================================

alter table public.kpi_metrics
  add column if not exists thresholds jsonb;

comment on column public.kpi_metrics.thresholds is
  'Гибкий список порогов: [{"key","label","value","color","karma","energy"}, ...], '
  'от самого мягкого к самому строгому. NULL = показатель использует старые '
  '4 столбца thr_min/thr_mid/thr_top/thr_ultra (обратная совместимость).';

alter table public.tasks
  add column if not exists auto_target_rank integer;

comment on column public.tasks.auto_target_rank is
  'Для авто-заданий с auto_metric_id: минимальный ранг порога (1 = самый '
  'мягкий уровень показателя, 2 = следующий, и т.д.), который нужно '
  'достичь по этому конкретному показателю за день. NULL, если задание '
  'использует общий auto_goal_condition (все/любой показатель) вместо '
  'привязки к одному конкретному.';

notify pgrst, 'reload schema';
