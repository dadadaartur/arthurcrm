-- момент выигрыша сохраняются здесь же (не берутся заново из
-- wheel_configs.prizes, потому что админ может позже поменять/удалить
-- приз в настройках — история должна остаться такой, какой была в
-- момент выигрыша, а не задним числом меняться).
