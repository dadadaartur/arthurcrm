alter table public.wheel_spin_history
  add column if not exists prize_color text,
  add column if not exists prize_avatar_url text,
  add column if not exists prize_description text;

comment on column public.wheel_spin_history.prize_color is
  'Цвет приза на момент выигрыша (снимок, не ссылка на текущую настройку — админ мог изменить его позже).';
comment on column public.wheel_spin_history.prize_avatar_url is
  'Необязательная картинка приза на момент выигрыша, тот же bucket avatars/public, что и у остальных изображений проекта.';
comment on column public.wheel_spin_history.prize_description is
  'Необязательное описание приза на момент выигрыша — показывается в истории покупок сотрудника.';

