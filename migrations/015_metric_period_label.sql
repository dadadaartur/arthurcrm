-- П.2 из большого списка фидбека (27 августа 2026): «нет явного понимания
-- дедлайна целей... красиво разделять ежедневные/еженедельные/
-- ежемесячные, значок с подсказкой правил обновления, настройка времени
-- у админа».
--
-- Period — по умолчанию 'daily', что соответствует тому, как показатели
-- фактически считались и раньше (текущее значение = сегодняшний ввод) —
-- ни одна существующая цель не меняет поведения, просто теперь у неё
-- есть явная, видимая подпись вместо неявного предположения.
-- ============================================================================

alter table public.kpi_metrics
  add column if not exists period text not null default 'daily';

alter table public.kpi_metrics
  add column if not exists reset_hour integer not null default 8;

comment on column public.kpi_metrics.period is
  'daily | weekly | monthly | quarterly — как часто обновляется шкала показателя, для понятной подписи и подсказки сотруднику. Не меняет расчёт значения (это делает kpi_type), только описание.';
comment on column public.kpi_metrics.reset_hour is
  'Час (0-23) по московскому времени, в который происходит обновление шкалы — для подсказки типа "обновляется ежедневно в 8:00 мск".';

