--
-- П.8 обратной связи от 26 августа 2026 — энергия набиралась за пару дней
-- вместо месяцев. Причина: энергия начисляется в 7 разных местах проекта
-- без единого ограничения, а поле auto_energy у авто-заданий вообще ничем
-- не ограничено при создании — если такое задание выполняется ежедневно,
-- одно задание может перекрыть месячный план за несколько дней.
--
-- Решение — дневной потолок на общую сумму энергии из ЛЮБых источников
-- сразу (пороги показателей, автозадания, тестирование), а не правка
-- каждого источника по отдельности до бесконечности. Два новых nullable/
-- со значением по умолчанию столбца у kpi_energy — какая сумма уже
-- начислена сегодня и когда был последний сброс счётчика.
-- ============================================================================

alter table public.kpi_energy
  add column if not exists today_granted integer not null default 0;

alter table public.kpi_energy
  add column if not exists today_date date;

comment on column public.kpi_energy.today_granted is
  'Сколько энергии уже начислено сегодня (все источники вместе) — для дневного потолка, см. lib/energy.js::creditEnergy.';
comment on column public.kpi_energy.today_date is
  'Дата, на которую считается today_granted — при смене дня счётчик обнуляется автоматически при следующем начислении.';

notify pgrst, 'reload schema';
