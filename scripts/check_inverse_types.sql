-- Проверка и исправление типа «инверсия» (пункты 3-4 фидбека от
-- 6 сентября 2026) — сравнение периодов показывало «стало хуже» для
-- SLA, которое реально уменьшилось (для SLA меньше = лучше), и «стало
-- лучше» для конверсии, которая реально упала. Формула сравнения
-- математически верна (проверено по коду), значит дело в том, что сами
-- показатели размечены не тем типом.

-- Шаг 1 — посмотрите, что сейчас: у показателей со словом SLA/время в
-- названии ожидаем kpi_type = 'inverse' (меньше — лучше). Если видите
-- другой тип у показателя с «SLA»/«время» в названии — это и есть
-- причина.
select id, name, kpi_type from public.kpi_metrics
where name ilike '%SLA%' or name ilike '%время%' or name ilike '%скорост%';

-- Шаг 2 — то же самое для конверсии: ожидаем 'ratio', НЕ 'inverse'.
select id, name, kpi_type from public.kpi_metrics
where name ilike '%конверси%' or name ilike '%CR%' or name ilike '%conversion%';

