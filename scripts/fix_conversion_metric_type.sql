-- Прямое исправление типа показателей конверсии (пункт 2 фидбека от
-- 6 сентября 2026) — вместо очередного «зайдите и поправьте сами»,
-- один раз находит по названию все показатели, где в имени есть слово
-- «конверси» или «CR», и у которых сейчас неверно стоит тип
-- «Накопительное» (суммирует за период — отсюда 1000%+, чего у доли
-- быть не может), и переключает на «Доля/конверсия» (усредняет).
--
-- Запустите файл целиком в SQL-редакторе Supabase — ничего вписывать
-- не нужно, поиск идёт по названию по всем вашим показателям сразу.
--
-- ⚠️ После смены типа стоит перепроверить сами пороговые числа
-- (мин/средний/топ/ультра) — при «Накопительном» они домножались на
-- число дней периода, при «Доле» — нет, старые числа могут больше не
-- подходить (например, если раньше «топ» был выставлен на 3000, а
-- честная доля не может быть больше 100).

update public.kpi_metrics
set kpi_type = 'ratio'
where kpi_type = 'cumulative'
  and (name ilike '%конверси%' or name ilike '%CR%' or name ilike '%conversion%');

-- Показывает, что именно было изменено — проверьте после запуска.
select id, name, kpi_type, thr_min, thr_mid, thr_top, thr_ultra
from public.kpi_metrics
where name ilike '%конверси%' or name ilike '%CR%' or name ilike '%conversion%';
